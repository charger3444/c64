#!/usr/bin/env python3
"""
FIDATI. (C64) - text/string table generator.
Converts plain uppercase ASCII strings into C64 screen-code byte
tables (Pascal-style: length byte followed by the code bytes), since
the game's custom charset only carries the "upper/graphics" ROM font.
"""

def to_screencode(s):
    out = []
    for c in s:
        if 'A' <= c <= 'Z':
            out.append(ord(c) - ord('A') + 1)
        elif 32 <= ord(c) <= 63:
            out.append(ord(c))
        else:
            raise ValueError("unsupported char %r in %r" % (c, s))
    return out

