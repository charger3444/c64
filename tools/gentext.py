def emit():
    out = ["; ---- AUTO-GENERATED by tools/gentext.py, do not hand-edit ----"]
    for label, s in STRINGS:
        codes = to_screencode(s)
        out.append("%s:" % label)
        out.append("    .byte %d" % len(codes))
        for i in range(0, len(codes), 16):
            chunk = codes[i:i+16]
            out.append("    .byte " + ",".join(str(b) for b in chunk))
    return "\n".join(out)

